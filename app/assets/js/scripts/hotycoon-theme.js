    function rects(grid, colors, ox = 0, oy = 0) {
        let out = ''
        grid.forEach((row, y) => {
            let x = 0
            while (x < row.length) {
                const k = row[x]
                if (k === '.' || !colors[k] || colors[k] === 'transparent') { x++; continue }
                let e = x; while (e < row.length && row[e] === k) e++
                out += `<rect x="${x + ox}" y="${y + oy}" width="${e - x}" height="1" fill="${colors[k]}"/>`
                x = e
            }
        })
        return out
    }
