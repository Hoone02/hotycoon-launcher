    function drawSprite(el) {
        const g = S[el.dataset.s]; if (!g || el.dataset.drawn) return
        const k = +(el.dataset.k || Z), w = g[0].length, h = g.length
        const ink = getComputedStyle(el).color, sh = shadeFor(el, ink)
        el.style.width = w * k + 'px'; el.style.height = (h + 1) * k + 'px'
        el.innerHTML = svg(w, h + 1, rects(g, { '#': sh }, 0, 1) + rects(g, { '#': 'currentColor' })).replace('<svg ', '<svg style="width:100%;height:100%;display:block" ')
        el.dataset.drawn = '1'
    }
    function drawSprites(root) {
        if (root.matches && root.matches('.spr[data-s]')) drawSprite(root)
        if (root.querySelectorAll) root.querySelectorAll('.spr[data-s]').forEach(drawSprite)
    }

