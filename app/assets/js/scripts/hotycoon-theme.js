    function rgb(c) {
        c = (c || '').trim()
        let m = c.match(/^#([0-9a-f]{6})$/i)
        if (m) return [0, 2, 4].map(i => parseInt(m[1].substr(i, 2), 16))
        m = c.match(/rgba?\(([^)]+)\)/i)
        if (m) { const p = m[1].split(/[ ,/]+/).filter(Boolean).map(Number); if (p.length > 3 && p[3] === 0) return null; return p.slice(0, 3) }
        return null
    }
    const hex = a => '#' + a.map(v => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('')
    function darker(c, k = 0.72) { const a = rgb(c); return a ? hex(a.map(v => v * k)) : 'transparent' }
    function mix(c1, c2, t) { const a = rgb(c1), b = rgb(c2); return a && b ? hex(a.map((v, i) => v + (b[i] - v) * t)) : c1 }
    function shade(c) { const d = darker(c, 0.86); return d === 'transparent' ? d : mix(d, '#6B2A4A', 0.12) }
    function shadeLine(c) { const d = darker(c, 0.72); return d === 'transparent' ? d : mix(d, '#6B2A4A', 0.18) }

