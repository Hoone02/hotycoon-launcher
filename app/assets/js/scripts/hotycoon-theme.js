    function nineGrid(shape) {
        const { c, dash } = shape, n = c.length, mw = dash ? 2 : 1, mh = 2
        const W = 2 * n + mw, H = 2 * n + mh, g = []
        const LOW = { f: 's', o: 'O', r: 'R' }
        for (let y = 0; y < H; y++) {
            let row = ''
            for (let x = 0; x < W; x++) {
                const cx = x < n ? x : x >= n + mw ? W - 1 - x : -1
                const cy = y < n ? y : y >= n + mh ? H - 1 - y : -1
                let k
                if (cx >= 0 && cy >= 0) k = c[cy][cx]
                else if (cy >= 0) { k = c[cy][n - 1]; if (dash && k === 'o' && (x - n) % 2 === 1) k = '.' }
                else if (cx >= 0) k = c[n - 1][cx]
                else k = c[n - 1][n - 1]
                if (y >= n + mh / 2) k = LOW[k] || k
                row += k
            }
            g.push(row)
        }
        return { g, W, H }
    }
    function nineImage(shape, o, f, r = 'transparent') {
        const { g, W, H } = nineGrid(SHAPES[shape])
        return uri(svg(W, H, rects(g, { o, f, r, s: shade(f), O: shadeLine(o), R: shadeLine(r) })))
    }

